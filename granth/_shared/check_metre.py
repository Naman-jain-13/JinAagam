# -*- coding: utf-8 -*-
"""छन्द से पाठ जाँचिए — अनुष्टुप् की पंक्ति 16 अक्षर की होती है।

चलाइए:  python check_metre.py <ग्रन्थ-फोल्डर>
        python check_metre.py . --all     # 8/16 के अलावा सब दिखाइए

## यह क्यों

इस परियोजना की सबसे ख़तरनाक भूल सन्दर्भ से शब्द बैठा देना है। वह पकड़ी नहीं
जाती: छपे पाठ जैसी दिखती है, व्याकरण ठीक रहता है, अर्थ भी बैठ जाता है।

**पर छन्द नहीं बैठता।** अनुष्टुप् का हर पाद 8 अक्षर का है, इसलिए छपी पंक्ति
16 अक्षर की। अक्षर छूटे या जोड़ा जाए तो गिनती टूट जाती है — और गिनती राय नहीं,
गणना है। एक बैच ने स्वयं लिखा "about 16 syllables" और उसी से उसकी कारिका-पंक्ति
पक्की हुई; दूसरे ने माना कि उसने यह जाँच श्लोकों पर लगाई ही नहीं। इसीलिए यह
औज़ार है — हाथ की गिनती छूट जाती है।

## यह क्या नहीं कर सकता

- **`[अस्पष्ट]` वाली पंक्ति नहीं गिनी जाती** — वहाँ कितने अक्षर छिपे हैं, यह
  पता नहीं। ऐसी पंक्तियाँ अलग से गिनकर बताई जाती हैं।
- **हर श्लोक अनुष्टुप् नहीं है।** आर्या, उपजाति और वृत्त-बद्ध श्लोक भी हैं, और
  उद्धृत श्लोक किसी भी छन्द में हो सकते हैं। इसलिए यह **चेतावनी देता है, निर्णय
  नहीं** — ठीक वैसे ही जैसे `check_scan_quality.py`।
## गिनती को पढ़ना कैसे है — यह सीधा नहीं है

इस औज़ार को बनाते समय तीन बातें निकलीं, और इनके बिना गिनती भ्रम देती है:

- **15 अक्षर प्रायः दोष नहीं, पाद-सन्धि है।** जब पहले पाद का अन्त और दूसरे का
  आरम्भ स्वर-सन्धि में जुड़ जाते हैं, तो छपे अक्षर एक कम हो जाते हैं पर छन्द
  16 का ही रहता है — *अविज्ञातथाभावस्य + अभ्युपायविरोधतः* →
  `अविज्ञातथाभावस्याभ्युपायविरोधतः`, 15 अक्षर। **इसलिए 15 को खटकने वाला माना
  जाता है, दोष नहीं।**
- **17–18 प्रायः सम्पादक के कोष्ठक से बनता है।** `अतीतानागतादीनामपि सत्ता
  [अनुषङ्गवत्]` में कोष्ठक ने सन्धि तोड़ दी; सन्धि-सहित `सत्तानुषङ्गवत्` से
  पंक्ति ठीक 16 की है। कोष्ठक हटाकर गिनने पर भी यह खटकता रहेगा — वह छपाई का
  रूप है, पाठ का दोष नहीं।
- **14 या उससे कम प्रायः सचमुच छूटा हुआ अक्षर है।** यही सबसे काम की चेतावनी है।

अर्थात् **यह औज़ार संशय की सूची बनाता है, दोष-सूची नहीं।** हर पंक्ति छपे पृष्ठ
पर देखकर ही तय होती है।
"""
import glob
import io
import re
import sys
import pathlib

try:
    sys.stdout.reconfigure(encoding="utf-8")
except (AttributeError, OSError):
    pass

CONS = set(range(0x0915, 0x093A)) | {0x0958 + i for i in range(8)}
VOWEL = set(range(0x0905, 0x0915))          # अ … औ
VIRAMA = 0x094D
MATRA = set(range(0x093E, 0x094D))          # ा … ् से पहले तक
SKIP = {0x0901, 0x0902, 0x0903, 0x093D, 0x0951, 0x0952}   # ँ ं ः ऽ स्वर-चिह्न


def aksharas(s):
    """संस्कृत अक्षर गिनिए — व्यंजन+स्वर एक अक्षर, हलन्त वाला समूह एक।"""
    n, i = 0, 0
    cp = [ord(c) for c in s]
    while i < len(cp):
        c = cp[i]
        if c in VOWEL:
            n += 1
        elif c in CONS:
            # हलन्त-जुड़े व्यंजन एक ही अक्षर बनाते हैं: क् + ष + ा = "क्षा"
            j, coda = i, False
            while j + 1 < len(cp) and cp[j + 1] == VIRAMA:
                if j + 2 < len(cp) and cp[j + 2] in CONS:
                    j += 2                      # समूह आगे बढ़ा
                else:
                    coda = True                 # पद के अन्त का हलन्त
                    break
            i = j
            # **अन्त का हलन्त व्यंजन अपना अक्षर नहीं बनाता** — `मतम्` दो अक्षर
            # (म, तम्) है, तीन नहीं। पहले यह गिना जा रहा था और हर हलन्त-अन्त
            # पंक्ति एक अक्षर बड़ी दिखती थी।
            if not (coda and n > 0):
                n += 1
        i += 1
    return n


# **केवल `1. मूल पाठ` खण्ड की, अङ्क-सहित पंक्तियाँ देखी जाती हैं।**
#
# दो दोष बनाते समय निकले और दोनों इसी जगह थे:
#
# 1. **पहला रूप हर `।`-वाली पंक्ति गिनता था** — पाठभेद-टिप्पणियाँ
#    (`(पृष्ठ 5, 2) महावीरे ।`) भी श्लोक समझ ली गईं, और भाग 1 में 2697 झूठी
#    चेतावनियाँ निकलीं। गद्य को छन्द से जाँचना निरर्थक है।
# 2. **दूसरा रूप हिन्दी अनुवाद भी गिन रहा था** — "ऐसा कहते हैं", "इसलिए श्लोक"
#    जैसी पंक्तियाँ, क्योंकि उनमें श्लोक-अङ्क का उल्लेख था। इसलिए अब दायरा
#    `## 1. मूल पाठ` खण्ड तक सीमित है, वैसे ही जैसे `check_shloka.py` में।
# 3. **`इति` बीच से हटाने पर गिनती दो कम हो जाती थी** — `चेन्नियमः कस्मात् इति
#    यः…` जैसी पंक्ति 14 दिखती थी। अब `इति` केवल पंक्ति के **अन्त** से हटता है,
#    जहाँ वह सचमुच श्लोक के बाहर होता है।
NUMBERED = re.compile(r"॥\s*[०-९\d]+\s*॥")
HAS_DEV = re.compile(r"[\u0900-\u097F]")
DROP = re.compile(r"[\[\]()*_—–\-'\"“”‘’?!,;:0-9०-९]")
TAIL_FILLER = re.compile(r"[\s।॥]*(इति|इत्यादि)[\s।॥]*$")
MOOL = re.compile(r"(?m)^##\s*1\.\s*मूल पाठ")

root = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else ".").resolve()
SHOW_OK = "--all" in sys.argv

files = sorted(glob.glob(str(root / "parts" / "*.md")))
if not files:
    sys.exit("parts/*.md नहीं मिली — ग्रन्थ-फोल्डर दीजिए")


def mool_blocks(raw):
    """केवल `## 1. मूल पाठ` वाले खण्ड लौटाइए — अनुवाद और व्याख्या छोड़कर।"""
    out = []
    for blk in re.split(r"(?m)^##\s", raw):
        if re.match(r"\s*1\.\s*मूल पाठ", blk):
            out.append(blk)
    return out


def segments(s):
    """अङ्क हटाकर `।`/`॥` पर तोड़िए — हर टुकड़ा आधा श्लोक (16) या पाद (8) हो।"""
    s = TAIL_FILLER.sub("", s)
    s = NUMBERED.sub(" ॥ ", s)
    s = DROP.sub(" ", s)
    out = []
    for seg in re.split(r"[।॥]", s):
        seg = TAIL_FILLER.sub("", seg.strip()).strip()
        if seg and HAS_DEV.search(seg):
            out.append(seg)
    return out


fits = suspect = unclear = long_ = 0
rows = []
for f in files:
    name = pathlib.Path(f).name
    raw = io.open(f, encoding="utf-8").read()
    page = None
    for ln in raw.split("\n"):
        m = re.match(r"^\(पृष्ठ (\d+)\)", ln)
        if m:
            page = m.group(1)
    # पृष्ठ-चिह्न मूल खण्ड के भीतर ही आते हैं, इसलिए खण्ड-वार चलिए
    for blk in mool_blocks(raw):
        page = None
        for ln in blk.split("\n"):
            m = re.match(r"^\(पृष्ठ (\d+)\)", ln.strip())
            if m:
                page = m.group(1)
            s = ln.strip().lstrip("*->  ").strip()
            if not s or "[उद्धरण" in s or not NUMBERED.search(s):
                continue
            if "[अस्पष्ट]" in s:
                unclear += 1
                continue
            for seg in segments(s):
                n = aksharas(seg)
                if n in (8, 16):
                    fits += 1
                    if SHOW_OK:
                        rows.append((name, page, n, seg))
                elif n > 18 or n < 6:
                    long_ += 1      # दूसरा छन्द, या टुकड़ा
                else:
                    suspect += 1
                    rows.append((name, page, n, seg))

print("`1. मूल पाठ` की अङ्क-सहित श्लोक-पंक्तियाँ")
print("  अनुष्टुप् पर बैठीं (8 या 16)   : %d" % fits)
print("  खटकने वाली (6-15, 17-18)      : %d" % suspect)
print("  18 से ऊपर / 6 से कम            : %d" % long_)
print("  [अस्पष्ट] के कारण छोड़ीं         : %d" % unclear)
print()
for name, page, n, seg in rows[:70]:
    print("%-24s पृ.%-4s %2d  %s" % (name[:24], page or "?", n, seg[:70]))
if len(rows) > 70:
    print("... और %d" % (len(rows) - 70))
print()
print("यह चेतावनी देता है, निर्णय नहीं। 15 प्रायः पाद-सन्धि है और 17 प्रायः")
print("सम्पादक का कोष्ठक। **14 या कम प्रायः सचमुच छूटा अक्षर है - वही देखिए।**")
