# -*- coding: utf-8 -*-
"""हर न्याय-ग्रन्थ के लिए हेत्वाभास-स्थल-सूची — कौन-सा हेत्वाभास कहाँ आया है।

चलाइए:  python _shared/make_hetvabhasa_index.py <ग्रन्थ-फ़ोल्डर>
        python _shared/make_hetvabhasa_index.py --all

## यह सूची क्यों, और वह नहीं जो पहले सोची गई थी

पहले विचार यह था कि ग्रन्थ में प्रतिपक्षी हेतु देता है पर हेत्वाभास का नाम नहीं लेता,
इसलिए पहचान कर बताई जाए। **नापने पर वह बात इन ग्रन्थों पर लागू नहीं निकली** — ये
तकनीकी न्याय-ग्रन्थ हैं और नाम स्वयं लेते हैं: प्रति अनुच्छेद 1.6 से 2.7 बार
(बृहत्-सर्वज्ञसिद्धि 2.7, अष्टसहस्री 2.2, प्रमेयकमल 1.6)। बृहत्-सर्वज्ञसिद्धि के
सत्तर अनुच्छेद पूरे पढ़ने पर केवल दो स्थल ऐसे मिले जहाँ कोटि अनाम रही, और वे भी
निश्चित नहीं।

इसलिए पाठक के लिए असली कठिनाई पहचान नहीं, **स्थान** है। विरले हेत्वाभास — जिन्हें
पाठक जीवन में दो-चार बार ही देखता है — पूरे ग्रन्थ में दो-चार जगह ही आते हैं, और
वही ढूँढ़ने में समय जाता है। प्रमेयकमल के 1752 अनुच्छेदों में व्यधिकरणासिद्ध केवल
दो स्थानों पर है, विरुद्धाव्यभिचारी एक पर।

यह सूची वही बताती है, और **पूरी तरह पाठ से निकलती है** — कोई अनुमान नहीं, कोई
कोटि-निर्णय नहीं। जो ग्रन्थ ने नाम लेकर कहा, वही यहाँ दर्ज है। विद्वान् पाठक इसे
स्वयं जाँच सकता है, और यही इसका बल है।
"""
import pathlib
import re
import sys

sys.stdout.reconfigure(encoding="utf-8")
HERE = pathlib.Path(__file__).resolve().parent
GRANTH = HERE.parent

# क्रम वही जो परिशिष्ट की सूची में है — पाठक दोनों साथ पढ़ता है।
GROUPS = [
    ("असिद्ध के भेद", ["स्वरूपासिद्ध", "आश्रयासिद्ध", "भागासिद्ध", "व्यधिकरणासिद्ध",
                        "सन्दिग्धासिद्ध", "संदिग्धासिद्ध", "विशेष्यासिद्ध",
                        "विशेषणासिद्ध", "अन्यथासिद्ध", "साध्यसम"]),
    ("अनैकान्तिक के भेद", ["सव्यभिचार", "साधारण अनैकान्तिक", "असाधारण अनैकान्तिक",
                            "अनुपसंहारी", "विरुद्धाव्यभिचारी"]),
    ("अन्य कोटियाँ", ["प्रकरणसम", "कालात्ययापदिष्ट", "अकिञ्चित्कर", "अकिंचित्कर"]),
]
# ये हर पन्ने पर हैं; इनकी स्थल-सूची देना सूची को ही निरर्थक कर देगा।
TOO_COMMON = {"असिद्ध", "विरुद्ध", "अनैकान्तिक"}


def sections(book):
    """(§ संख्या, पूरा पाठ) — parts/ और addenda/ दोनों से।"""
    out = {}
    p = book / "parts"
    if p.exists():
        for f in sorted(p.glob("*.md")):
            for blk in re.split(r"(?m)^(?=§\d)", f.read_text(encoding="utf-8", errors="replace")):
                m = re.match(r"§(\d+)", blk)
                if m:
                    out.setdefault(int(m.group(1)), []).append(blk)
    a = book / "addenda"
    if a.exists():
        for f in a.glob("s*.md"):
            if f.stem[1:].isdigit():
                out.setdefault(int(f.stem[1:]), []).append(
                    f.read_text(encoding="utf-8", errors="replace"))
    return {k: "\n".join(v) for k, v in out.items()}


def build(book):
    secs = sections(book)
    if not secs:
        return None
    lines = ["# परिशिष्ट — हेत्वाभास के स्थल", "",
             "यह सूची बताती है कि इस ग्रन्थ में कौन-सा हेत्वाभास कहाँ आया है। हेत्वाभासों के",
             "लक्षण और पहचान के लिए पिछला परिशिष्ट देखिए; यह उसका स्थल-निर्देश है।", "",
             "यहाँ वही दर्ज है जो ग्रन्थ ने **नाम लेकर** कहा — कोई कोटि अनुमान से नहीं लगाई गई।",
             "असिद्ध, विरुद्ध तथा अनैकान्तिक — ये तीनों इस ग्रन्थ में इतनी बार आते हैं कि उनकी",
             "स्थल-सूची देना निरर्थक होता; इसलिए यहाँ उनके **भेद** दिए गए हैं, जो विरले हैं और",
             "जिन्हें ढूँढ़ने में ही समय जाता है।", ""]
    found_any = False
    for title, terms in GROUPS:
        rows = []
        for t in terms:
            if t in TOO_COMMON:
                continue
            hit = sorted(n for n, txt in secs.items() if t in txt)
            if hit:
                ref = ", ".join(f"§{n}" for n in hit)
                rows.append(f"| {t} | {len(hit)} | {ref} |")
        if rows:
            found_any = True
            lines += [f"## {title}", "", "| हेत्वाभास | स्थल | अनुच्छेद |", "|---|---:|---|"] + rows + [""]
    if not found_any:
        return None
    lines += ["इनमें जिनके सामने एक या दो ही अनुच्छेद हैं, वे इस ग्रन्थ के दुर्लभ स्थल हैं —",
              "उन्हीं को देखकर पाठक उस कोटि का वास्तविक रूप पहचान सकता है।", ""]
    # "अन्यथासिद्ध" दो अर्थों में चलता है और सूची उन्हें अलग नहीं कर सकती, इसलिए
    # पाठक को यहीं सावधान कर देना ठीक है। प्रमेयकमल §954 में वह कारणता वाला अर्थ है,
    # हेत्वाभास वाला नहीं — बिना चेतावनी के पाठक उसे हेत्वाभास समझ लेता।
    if any("अन्यथासिद्ध |" in l for l in lines):
        lines += ["**एक सावधानी —** 'अन्यथासिद्ध' शब्द दो अर्थों में आता है: एक हेत्वाभास के रूप में,",
                  "और दूसरा कारणता-विचार में ('अन्यथासिद्धि' — जो वस्तुतः कारण नहीं, उसका कारण-रूप से",
                  "निरास)। यह सूची दोनों को अलग नहीं कर सकती, इसलिए इस पंक्ति के स्थल देखते समय",
                  "प्रसंग से ही निर्णय कीजिए।", ""]
    return "\n".join(lines) + "\n"


def main(args):
    books = ([d for d in sorted(GRANTH.iterdir()) if (d / "parts").exists()]
             if "--all" in args else [GRANTH / a for a in args if not a.startswith("--")])
    for b in books:
        txt = build(b)
        if not txt:
            print(f"  {b.name:<26} कोई हेत्वाभास-भेद नहीं मिला — छोड़ा")
            continue
        out = b / "backmatter"
        out.mkdir(exist_ok=True)
        (out / "90_hetvabhasa_sthal.md").write_text(txt, encoding="utf-8")
        n = txt.count("| §") + txt.count(", §")
        print(f"  {b.name:<26} backmatter/90_hetvabhasa_sthal.md — "
              f"{len([l for l in txt.splitlines() if l.startswith('| ') and 'हेत्वाभास |' not in l])} कोटियाँ")


if __name__ == "__main__":
    main(sys.argv[1:])
