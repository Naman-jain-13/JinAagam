# -*- coding: utf-8 -*-
"""विवरण-श्लोकों के क्रमांक लगातार हैं या नहीं — पूरे ग्रन्थ पर एक साथ।

चलाइए:  python check_shloka.py

## यह क्यों बना

श्री वादिराजसूरि के अपने विवरण-श्लोक पूरे ग्रन्थ में **एक ही क्रम** में चलते हैं —
॥१॥ से आगे, बिना टूटे। इसलिए उनका क्रम स्वयं एक जाँच है: यदि किसी बैच में अङ्क
पीछे चला जाए या छलाँग लगा दे, तो वह प्रायः पढ़ने की भूल है, छपाई की नहीं।

यह जाँच एक सच्ची भूल से निकली। एक बैच ने मुद्रित 105–110 के श्लोक ॥२०८॥–॥२२७॥
पढ़े थे; वे वस्तुतः ॥३०८॥–॥३२७॥ थे। कारण: **इस छपाई में `३` का ऊपरी वक्र दबकर
`२` जैसा दिखता है।** उसने स्वयं पकड़ा, पर केवल इसलिए कि उसने पिछले बैच के ॥३०७॥
से जोड़कर देखा। अकेले पन्ने को देखकर यह कभी नहीं पकड़ा जाता — दोनों अङ्क अपने आप
में ठीक दिखते हैं।

सौ का फ़र्क़ ख़ास तौर पर ख़तरनाक है: १०८/२०८/३०८ तीनों एक-से छपते हैं और तीनों
सम्भव लगते हैं।

## यह क्या नहीं कर सकता — पढ़कर ही आगे बढ़िए

**यह विवरण-श्लोक और उद्धृत श्लोक में भेद नहीं कर सकती**, और यही इसकी सबसे बड़ी
सीमा है। भाग 1 में तीन तरह के `॥N॥` आते हैं:

1. श्री वादिराजसूरि के अपने **विवरण-श्लोक** — एक ही लगातार क्रम, यही जाँच का विषय
2. श्री अकलङ्कदेव की **मूल कारिका** — अलग क्रम, बहुत विरल
3. **दूसरे ग्रन्थों से उद्धृत श्लोक** — उनका अपना क्रम, कहीं से भी आ सकता है

तीसरा वर्ग हर "पीछे गया" को सन्देहास्पद बना देता है। एक बार ऐसा हुआ: मुद्रित 92
पर ॥२९३॥ और मुद्रित 99 पर ॥२९५॥ के बीच मुद्रित 98 पर ॥१९४॥ दिखा, और अंकगणित से
वह ॥२९४॥ लगा। पर उसी पृष्ठ पर **सिद्धिविनिश्चय का उद्धृत श्लोक** है — अर्थात्
॥१९४॥ उसका अपना अङ्क हो सकता है, और "सुधार" करना ग़लत होता।

इसलिए यह जाँच **बताती है, बदलती नहीं।** हर चेतावनी पर पहले यह देखिए कि वह श्लोक
उद्धरण तो नहीं है; तभी अङ्क पर सन्देह कीजिए।

छेद भी हमेशा भूल नहीं होता: कहीं अङ्क छपा ही नहीं (एक पृष्ठ पर ॥२२१॥ नहीं मिला),
कहीं बीच के पृष्ठ अभी लिखे ही नहीं गए, कहीं पृष्ठ प्रति में नहीं है।
"""
import glob
import io
import re
import sys
import pathlib

try:
    sys.stdout.reconfigure(encoding="utf-8")
except (AttributeError, OSError):
    pass

HERE = pathlib.Path(__file__).resolve().parent
DEV = "०१२३४५६७८९"
NAME = re.compile(r"batch(\d+)_p(\d+)-(\d+)")
PAGE = re.compile(r"^\(पृष्ठ (\d+)\)", re.M)
# ॥३०८॥ — दोनों ओर दण्ड-युग्म, भीतर केवल देवनागरी अङ्क
SHLOKA = re.compile(r"॥\s*([०-९]{1,4})\s*॥")


def dev_int(s):
    return int("".join(str(DEV.index(c)) for c in s))


found = []
for f in sorted(glob.glob(str(HERE / "parts" / "batch*.md"))):
    m = NAME.search(pathlib.Path(f).name)
    lo = int(m.group(2))
    raw = io.open(f, encoding="utf-8").read()
    # **केवल भाग 1 (मूल पाठ) देखिए।** पूरी फ़ाइल पर चलाने से जाँच बेकार हो जाती है:
    # वही अङ्क अनुवाद और व्याख्या में भी उद्धृत होते हैं ("श्लोक ॥२३८॥ में कहा…"),
    # शीर्षकों में परास लिखी जाती है, और उद्धृत दूसरे ग्रन्थों के अपने श्लोक-अङ्क
    # भी ॥१॥ से चलते हैं। पहली बार चलाने पर 51 "खटके" आए और उनमें अधिकांश यही शोर था।
    text = "\n".join(
        blk for blk in re.split(r"(?m)^##\s", raw) if blk.startswith("1. मूल पाठ"))
    # पृष्ठ-चिह्न और श्लोक-अङ्क एक ही क्रम में पढ़िए, ताकि हर श्लोक अपने पृष्ठ से
    # जुड़ जाए — अन्यथा छलाँग किस पन्ने पर है यह बताया नहीं जा सकता।
    cur = lo
    for mm in re.finditer(r"^\(पृष्ठ (\d+)\)|॥\s*([०-९]{1,4})\s*॥", text, re.M):
        if mm.group(1):
            cur = int(mm.group(1))
        else:
            found.append((cur, dev_int(mm.group(2)), pathlib.Path(f).name))

found.sort(key=lambda r: (r[0],))
print("विवरण-श्लोक मिले: %d" % len(found))
if not found:
    sys.exit(0)

probs = []
prev_n, prev_p, prev_f = None, None, None
for page, n, fn in found:
    if prev_n is not None:
        if n == prev_n:
            pass                      # एक ही श्लोक दो बार उद्धृत — सामान्य
        elif n < prev_n:
            probs.append("पीछे गया: मुद्रित %d पर ॥%d॥, पर मुद्रित %d पर ॥%d॥ था (%s)"
                         % (page, n, prev_p, prev_n, fn))
        elif n - prev_n > 1:
            probs.append("छलाँग: मुद्रित %d पर ॥%d॥ के बाद मुद्रित %d पर ॥%d॥ (%s)"
                         % (prev_p, prev_n, page, n, fn))
    prev_n, prev_p, prev_f = n, page, fn

print("परास: ॥%d॥ (मुद्रित %d) से ॥%d॥ (मुद्रित %d)"
      % (found[0][1], found[0][0], found[-1][1], found[-1][0]))
print("खटके: %d\n" % len(probs))
for p in probs:
    print("  - %s" % p)
if probs:
    print("\nसौ का फ़र्क़ (१०८/२०८/३०८) सबसे अधिक धोखा देता है — `३` का ऊपरी वक्र")
    print("दबकर `२` जैसा दिखता है। छलाँग दिखे तो पड़ोसी बैच से जोड़कर देखिए।")
    print("हर खटका भूल नहीं — कहीं अङ्क छपा ही नहीं, कहीं पृष्ठ प्रति में नहीं है।")
