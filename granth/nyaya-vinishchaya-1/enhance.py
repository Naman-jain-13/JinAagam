"""धुँधले पन्ने को पढ़ने लायक़ बनाने के लिए — काटिए, साफ़ कीजिए, बड़ा कीजिए।

चलाइए:
    python enhance.py 45                 # पूरा पृष्ठ, तीन पट्टियों में
    python enhance.py 45 --from .62 --to .90   # केवल यह हिस्सा (पाद-टिप्पणी)
    python enhance.py 45 --scale 5       # और बड़ा
    python enhance.py 45 --cols 1        # बिना बाएँ-दाएँ काटे (चौड़ी पंक्ति के लिए)

मुद्रित पृष्ठ-संख्या दीजिए, स्कैन की नहीं — pagemap.json से अपने आप बैठ जाएगी।
बनी हुई छवियाँ scratchpad में जाती हैं, ग्रन्थ-फ़ोल्डर में नहीं, और उनका पथ
छप जाता है; उसी को Read से खोलिए।

## यह क्यों

कुछ पन्नों पर स्याही फैली है और टाइप भर गया है — मुद्रित 41 से 45 तक विशेषकर।
सीधे पढ़ने पर वहाँ बहुत कुछ [अस्पष्ट] रह जाता है, जबकि विषमता सुधारकर और
किनारे तीखे करके वही अक्षर पढ़े जा सकते हैं। मुद्रित 45 की टिप्पणी (4) पूरी
अपठनीय मानी गई थी; इस उपचार के बाद वह पढ़ी गई।

**फिर भी जो न पढ़ा जाए, वह [अस्पष्ट] ही रहे।** यह उपकरण अनुमान लगाने की छूट
नहीं देता — केवल आँख को वह दिखाता है जो स्याही में दबा रह गया था।
"""
import pathlib
import os
import tempfile
import sys

from PIL import Image, ImageFilter, ImageOps

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import page as pagemap  # noqa: E402

try:
    sys.stdout.reconfigure(encoding="utf-8")
except (AttributeError, OSError):
    pass

HERE = pathlib.Path(__file__).resolve().parent
# **स्थिर जगह।** पहले यह किसी पुराने सत्र के scratchpad की ओर इशारा करता था
# (सहोदर ग्रन्थ से नक़ल होकर आया हुआ), इसलिए छवियाँ वहाँ बनती थीं जहाँ कोई
# देख नहीं रहा था। सत्र बदलने पर वह पथ फिर बासी हो जाता, इसलिए अब सत्र से
# बिलकुल स्वतन्त्र जगह है।
# हर चलाने की अपनी निर्देशिका (प्रक्रिया-संख्या से): पहले सब एजेंट एक ही `nv_enh` में
# `enh_pNNN_k.png` लिखते थे और कोई दूसरा उसी पृष्ठ पर चलाए तो फ़ाइल बदल जाती थी —
# एक बैच को मुद्रित 102 की पट्टी 1 दूसरे पृष्ठ-भाग की मिली। छपा पथ ही असली पथ है।
OUT = pathlib.Path(tempfile.gettempdir()) / "nv_enh" / ("run%d" % os.getpid())


# दिखाने की सीमा लगभग 2000 पिक्सेल चौड़ाई है। उससे चौड़ी छवि वापस घटा दी जाती
# है, इसलिए **गुणा करने से नहीं, चौड़ाई घटाने से** अक्षर बड़े मिलते हैं।
#
# यहाँ एक और पेच है: `img/` की छवियाँ 200 dpi पर बनी हैं (लगभग 2042 px चौड़ी),
# जबकि स्कैन में सूचना केवल 735 px की है। इसलिए "4x" जैसा गुणा 4132 px दे देता
# था — सीमा से दुगुना, और वापस घटकर वही 2.7x। दो एजेंटों ने ठीक यही बताया था
# कि "scale 3 पर कुछ अधिक नहीं खुलता"।
#
# अब पैमाना नहीं, **लक्ष्य-चौड़ाई** तय होती है: टुकड़ा जितना सँकरा होगा, अक्षर
# उतने ही बड़े दिखेंगे। आधे पन्ने पर यह लगभग 5x के बराबर पड़ता है।
TARGET_W = 1900


def enhance(img, scale=None):
    img = ImageOps.autocontrast(img, cutoff=2)
    img = img.filter(ImageFilter.UnsharpMask(radius=3, percent=180, threshold=2))
    f = TARGET_W / float(img.width)
    return img.resize((int(img.width * f), int(img.height * f)), Image.LANCZOS)


def main(argv):
    if not argv:
        print(__doc__)
        return 1
    printed = int(argv[0])
    g = lambda k, d: (float(argv[argv.index(k) + 1]) if k in argv else d)
    lo, hi, scale = g("--from", 0.0), g("--to", 1.0), g("--scale", 4.0)
    # **हाशिया पहले काटिए।** हर पन्ने के बाएँ किनारे पर जिल्द की चौड़ी काली पट्टी
    # है और दाएँ कुछ ख़ाली। वे पाठ नहीं हैं, पर चौड़ाई खा जाते हैं — और चौड़ाई ही
    # यहाँ बड़ाई तय करती है। उन्हें काटने भर से अक्षर बड़े हो जाते हैं, और पंक्ति
    # भी पूरी बनी रहती है।
    #
    # यह एक बैच के सुझाव से आया। वह आधे-आधे टुकड़ों (अ/ब) से असन्तुष्ट था:
    # "पंक्ति के बीच का शब्द बार-बार कट जाता है, और बायाँ आधा जिल्द की काली
    # पट्टी से घिरा रहता है" — उसने पूरी-चौड़ाई की हाशिया-कटी पट्टियाँ कहीं
    # अधिक पठनीय पाईं। इसलिए अब वही **पूर्वनिर्धारित** है; `--cols 2` या 3
    # केवल उन पंक्तियों के लिए जो तब भी न खुलें।
    mx0, mx1 = g("--left", 0.10), g("--right", 0.97)

    scan = pagemap.printed_to_scan.get(printed)
    if not scan:
        print(f"  मुद्रित {printed}: सारणी में नहीं — pagemap.json देखिए")
        return 1
    im = Image.open(HERE / f"img/p{scan:03d}.png").convert("L")
    W, H = im.size
    band = im.crop((int(W * mx0), int(H * lo), int(W * mx1), int(H * hi)))

    OUT.mkdir(parents=True, exist_ok=True)
    # एक साथ बहुत ऊँची पट्टी पढ़ने में कठिन होती है, इसलिए तीन टुकड़े
    n = 1 if (hi - lo) <= 0.30 else 3
    step = band.height // n

    # **चौड़ाई घटाए बिना पैमाना बढ़ाने का कोई लाभ नहीं।** दो एजेंटों ने स्वतन्त्र
    # रूप से यही बताया — "scale 3 पर कुछ अधिक नहीं खुलता" — और कारण यह है कि
    # 735 पिक्सेल चौड़ा पन्ना 3x पर 2205 का हो जाता है, जो दिखाने की सीमा से
    # ऊपर है और वापस घटा दिया जाता है। अर्थात् 2.7x से ऊपर सब बराबर।
    #
    # इसलिए पन्ने को बाएँ-दाएँ आधे में काटकर दिया जाता है: आधी चौड़ाई पर वही
    # सीमा 5x तक सँभाल लेती है, और अक्षर सचमुच दुगुने बड़े मिलते हैं।
    cols = int(g("--cols", 1))
    cw = band.width // cols
    out = []
    for i in range(n):
        top = i * step
        bot = band.height if i == n - 1 else (i + 1) * step
        for c in range(cols):
            # टुकड़ों के बीच थोड़ा ढाँप रखिए, वरना सन्धि पर अक्षर कट जाता है
            x0 = max(0, c * cw - 12)
            x1 = band.width if c == cols - 1 else min(band.width, (c + 1) * cw + 12)
            part = band.crop((x0, top, x1, bot))
            # हर टुकड़े का नाम अलग होना चाहिए। पहले यह `अ`/`ब` पर चलता था,
            # इसलिए `--cols 3` माँगने पर तीसरा टुकड़ा दूसरे पर लिख जाता था और
            # केवल दो फ़ाइलें बचती थीं — एक बैच ने यही बताया। अब अक्षर-सूची से
            # नाम बनता है, इसलिए जितने टुकड़े कहिए उतने बनते हैं।
            letters = "अबसदपफ"
            tag = f"{i + 1}" if cols == 1 else f"{i + 1}{letters[c]}"
            p = OUT / f"enh_p{printed}_{tag}.png"
            enhance(part, scale).save(p)
            out.append(p)
    for p in out:
        print(f"  {p}")
    print(f"  (मुद्रित {printed} = स्कैन {scan}; {n}×{cols} टुकड़े, {scale}x)")
    if cols > 1:
        print("  टुकड़े बाएँ से दाएँ: अ, ब, स … — पूरी पंक्ति के लिए सब देखिए।")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
