# -*- coding: utf-8 -*-
"""दसवीं जाँच — जहाँ पाठ संशय में है पर अनुवाद निश्चय जताता है।

यह दोष चार अलग-अलग परासों में अलग-अलग पाठकों ने पकड़ा (§1927, §2112, §2302,
§2315), हर बार हाथ से। उतनी बार मिलने के बाद उसे जाँच बन जाना चाहिए।

जो जाँचा जाता है: भाग 1 में [अस्पष्ट] है, पर भाग 2 का पाठक उसे देख ही नहीं
पाता। अनुवाद का काम मूल का छेद भर देना नहीं है; भर देने पर पता ही नहीं चलता कि
वाक्य ग्रन्थकार का है या हमारा।

## जो यहाँ नहीं जाँचा जा सका — और क्यों

§2112 का रूप इससे भिन्न है: वहाँ मूल में [अस्पष्ट] नहीं, एक मुद्रण-दोष है
("अग्निखभावः", जहाँ `ख` वस्तुतः `स्व`); पाद-टिप्पणी उसे "सम्भवतः स्वभावः" कहती
है और अनुवाद पूरे निश्चय से "अग्नि-स्वभाव वाला" देता है।

इसे भी जाँच बनाने की कोशिश की गई — "पाद-टिप्पणी संशय कहे पर अनुवाद निश्चय जताए"।
वह **दो बार** लिखी गई और दोनों बार ऐसे § पर लगी जिनकी संख्या कुल के बराबर थी:
पहली सूची से 21/21, दूसरी से 15/15। जो जाँच सब पर लगे, वह ग्रन्थ के बारे में
कुछ नहीं बताती — अपने बारे में बताती है।

कारण स्पष्ट है: इस संस्करण की टिप्पणी-शैली में "सम्भवतः" सुधार दर्ज करने का
सामान्य ढंग है, संशय का सूचक नहीं। "मुद्रित पाठ में 'मेदाऽमेदयोः' छपा है …
सम्भवतः 'भेदाभेदयोः'" — यह निर्णय है, दुविधा नहीं, और वहाँ अनुवाद का निश्चय
ठीक ही है। शब्द से यह भेद नहीं किया जा सकता।

इसलिए वह नियम हटा दिया गया, तीसरी सूची बनाकर ठीक दिखने वाली संख्या निकालने के
बजाय। यह दोष पढ़कर ही पकड़ा जा सकता है, और `_recheck/flagged_by_addenda.md`
में उसी रूप में रहता है। **इसे फिर जाँच बनाने का प्रयत्न न कीजिए** — यहाँ
दो बार विफल हो चुका है।

चलाइए:  python check_hedge.py              # सब बैच
        python check_hedge.py batch47      # एक बैच
"""
import re
import sys
import pathlib

sys.stdout.reconfigure(encoding="utf-8")

HERE = pathlib.Path(__file__).resolve().parent
MARK = "[अस्पष्ट]"

# संशय दिखाने के वे ढंग जो अनुवाद में चलते हैं।
#
# यह सूची पहले उदार थी और इसी कारण अपने ही प्रेरक उदाहरण छोड़ गई: "अनुमान" और
# "अनिश्चित" उसमें संशय-सूचक के रूप में थे, जबकि इस ग्रन्थ में "अनुमान" प्रमाण का
# नाम है और "अनिश्चित" ठीक "अनैकान्तिक" का अनुवाद। अतः §2302 और §2315 अपने ही
# विषय-शब्दों के बल पर जाँच से बच निकले।
#
# इसलिए अब केवल वे शब्द हैं जो **छपे पन्ने के बारे में ही हो सकते हैं** — दर्शन की
# शब्दावली से जिनका टकराव सम्भव नहीं। ज्ञान-विषयक सामान्य शब्द (अनुमान, अनिश्चित,
# सन्दिग्ध, प्रतीत होता, शायद) जान-बूझकर हटाए गए: वे इस पुस्तक में विषय हैं,
# टिप्पणी नहीं।
HEDGE = ["[अस्पष्ट", "अपठनीय", "दुष्पाठ्य", "मुद्रण", "छपाई",
         "पाठ अनिश्चित", "पाठ-भेद", "पाठ अस्पष्ट", "पाठ संदिग्ध",
         "सम्भवतः", "संभवतः", "स्पष्ट नहीं", "पढ़ा नहीं", "वाचन अनिश्चित"]

# ऊपर `[अस्पष्ट` बिना बन्द-कोष्ठक के है, जान-बूझकर: अनुवाद में चिह्न कभी-कभी
# खुला आता है — "[अस्पष्ट-संज्ञप्ति मानी जाए]" — और पूरा `[अस्पष्ट]` ढूँढ़ने पर
# वह छूट जाता था (§665)।
#
# और यह भी निकला कि संशय वाक्य में बिखरा हो सकता है: "(मूल पाठ में इस स्थान पर
# एक शब्द अस्पष्ट है)" — यहाँ "पाठ" और "अस्पष्ट" के बीच पाँच शब्द हैं, इसलिए
# "पाठ अस्पष्ट" से मेल नहीं खाया (§1557)। उसके लिए यह:
HEDGE_RE = re.compile(
    r"(?:पाठ|शब्द|अक्षर|पंक्ति|मुद्रण|स्थान|अंश)[^।\n]{0,40}?अस्पष्ट"
    r"|अस्पष्ट[^।\n]{0,20}?(?:पाठ|शब्द|अक्षर|मुद्रण)")

# बिना किसी सन्दर्भ के अकेला "अस्पष्ट" यहाँ नहीं रखा जा सकता — द्वितीय परिच्छेद
# में "स्पष्ट/अस्पष्ट प्रतिभास" प्रत्यक्ष का लक्षण-भेद है, विषय है, टिप्पणी नहीं।


def shows_doubt(part2):
    return any(h in part2 for h in HEDGE) or bool(HEDGE_RE.search(part2))


def parts_of(block):
    """§ के तीन भाग अलग-अलग — शीर्षक से काटकर।"""
    out = {}
    for n in (1, 2, 3):
        m = re.search(r"##\s*%d\..*?\n(.*?)(?=\n##\s*\d\.|\Z)" % n, block, re.S)
        out[n] = m.group(1) if m else ""
    return out


def main(only=None):
    files = sorted(HERE.glob("parts/batch*.md"))
    if only:
        files = [f for f in files if only in f.name]

    bad, total = [], 0
    for f in files:
        text = f.read_text(encoding="utf-8")
        batch = f.name.split("_")[0]
        for b in re.split(r"(?m)^(?=§\d)", text):
            m = re.match(r"§(\d+)", b)
            if not m:
                continue
            n = int(m.group(1))
            p = parts_of(b)
            pages = re.findall(r"\(\s*पृष्ठ\s*(\d+)", b)
            pg = pages[0] if pages else "?"
            shown = shows_doubt(p[2])

            # पाद-टिप्पणी की पंक्तियाँ छोड़ दीजिए। वहाँ का [अस्पष्ट] प्रायः
            # स्रोत-चिह्न या महीन टाइप के बारे में होता है, मूल की किसी सामग्री
            # के बारे में नहीं — यानी अनुवाद में भरने को कोई गड्ढा है ही नहीं।
            # §251 इसी कारण झूठा पकड़ा गया था।
            body = "\n".join(ln for ln in p[1].splitlines()
                             if not ln.strip().lstrip("*_- ").startswith("पाद-टिप्पणी"))
            n_marks = body.count(MARK)
            if not n_marks:
                continue
            total += 1
            if not shown:
                bad.append((n, batch, pg, n_marks))

    print(f"मूल में [अस्पष्ट] वाले §: {total} | "
          f"जिनका अनुवाद वह संशय नहीं दिखाता: {len(bad)}")
    print()
    for n, bt, pg, k in bad:
        print(f"  §{n:<5} {bt:<9} मुद्रित {pg:<5} "
              f"भाग 1 में {k} चिह्न, भाग 2 में कोई संकेत नहीं")
    if bad:
        print()
        print("अनुवाद वहीं तक जाये जहाँ तक मूल जाता है — या कोष्ठक में संशय "
              "दिखाये।\nपाठक अनुवाद पहले पढ़ता है, पाद-टिप्पणी बाद में।")


if __name__ == "__main__":
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    main(args[0] if args else None)
